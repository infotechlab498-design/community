using Community.Api.Models;
using Community.Api.Models.WaterSupply;
using Microsoft.EntityFrameworkCore;

namespace Community.Api.Data;

public class ApplicationDbContext : DbContext
{
    public ApplicationDbContext(
        DbContextOptions<ApplicationDbContext> options)
        : base(options)
    {
    }

    public DbSet<Admin> Admins => Set<Admin>();

    public DbSet<WaterSchedule> WaterSchedules => Set<WaterSchedule>();

    public DbSet<WaterSupplyBlock> WaterSupplyBlocks => Set<WaterSupplyBlock>();

    public DbSet<WaterSupplySchedule> WaterSupplySchedules => Set<WaterSupplySchedule>();

    public DbSet<WaterSupplyDay> WaterSupplyDays => Set<WaterSupplyDay>();

    public DbSet<WaterSupplyDayBlock> WaterSupplyDayBlocks => Set<WaterSupplyDayBlock>();

    public DbSet<PrayerTime> PrayerTimes => Set<PrayerTime>();

    public DbSet<ShuttleRoute> ShuttleRoutes => Set<ShuttleRoute>();

    public DbSet<ShuttleDeparture> ShuttleDepartures => Set<ShuttleDeparture>();

    public DbSet<GymSession> GymSessions => Set<GymSession>();

    public DbSet<Contact> Contacts => Set<Contact>();

    public DbSet<Hospital> Hospitals => Set<Hospital>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        modelBuilder.Entity<Admin>(entity =>
        {
            entity.HasKey(a => a.Id);

            entity.Property(a => a.Email)
                .HasMaxLength(256)
                .IsRequired();

            entity.HasIndex(a => a.Email)
                .IsUnique();

            entity.Property(a => a.PasswordHash)
                .IsRequired();
        });

        modelBuilder.Entity<WaterSchedule>(entity =>
        {
            entity.ToTable("WaterSchedules");
            entity.HasKey(x => x.Id);

            // Weekday IDs are fixed, not generated by SQL Server.
            entity.Property(x => x.Id).ValueGeneratedNever();
            entity.Property(x => x.Day).HasMaxLength(20).IsRequired();
            entity.Property(x => x.Time).HasMaxLength(150).IsRequired();
            entity.Property(x => x.Status).HasMaxLength(10).IsRequired();
        });

        modelBuilder.Entity<WaterSupplyBlock>(entity =>
        {
            entity.ToTable("WaterSupplyBlocks");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Id).HasMaxLength(10);
            entity.Property(x => x.Name).HasMaxLength(100).IsRequired();
        });

        modelBuilder.Entity<WaterSupplySchedule>(entity =>
        {
            entity.ToTable("WaterSupplySchedules");
            entity.HasKey(x => x.Id);
            entity.HasIndex(x => new { x.Year, x.Month }).IsUnique();
        });

        modelBuilder.Entity<WaterSupplyDay>(entity =>
        {
            entity.ToTable("WaterSupplyDays");
            entity.HasKey(x => x.Id);
            entity.HasIndex(x => new { x.ScheduleId, x.Date }).IsUnique();
            entity.Property(x => x.Date).HasColumnType("date");

            entity.HasOne(x => x.Schedule)
                .WithMany(x => x.Days)
                .HasForeignKey(x => x.ScheduleId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<WaterSupplyDayBlock>(entity =>
        {
            entity.ToTable("WaterSupplyDayBlocks");
            entity.HasKey(x => new { x.WaterSupplyDayId, x.BlockId });

            entity.HasOne(x => x.Day)
                .WithMany(x => x.BlockAssignments)
                .HasForeignKey(x => x.WaterSupplyDayId)
                .OnDelete(DeleteBehavior.Cascade);

            entity.HasOne(x => x.Block)
                .WithMany(x => x.DayAssignments)
                .HasForeignKey(x => x.BlockId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<PrayerTime>(entity =>
        {
            entity.ToTable("PrayerTimes");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Id).ValueGeneratedNever();
            entity.Property(x => x.Name).HasMaxLength(20).IsRequired();
            entity.HasIndex(x => x.Name).IsUnique();
            entity.Property(x => x.Time).HasMaxLength(5).IsRequired();
        });

        modelBuilder.Entity<ShuttleRoute>(entity =>
        {
            entity.ToTable("ShuttleRoutes");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Id).HasMaxLength(30);
            entity.Property(x => x.Origin).HasMaxLength(100).IsRequired();
            entity.Property(x => x.Destination).HasMaxLength(100).IsRequired();
        });

        modelBuilder.Entity<ShuttleDeparture>(entity =>
        {
            entity.ToTable("ShuttleDepartures");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Time).HasMaxLength(5).IsRequired();

            entity.HasOne(x => x.Route)
                .WithMany(x => x.Departures)
                .HasForeignKey(x => x.RouteId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<GymSession>(entity =>
        {
            entity.ToTable("GymSessions");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Title).HasMaxLength(100).IsRequired();
            entity.Property(x => x.Audience).HasMaxLength(10).IsRequired();
            entity.Property(x => x.StartTime).HasMaxLength(5).IsRequired();
            entity.Property(x => x.EndTime).HasMaxLength(5).IsRequired();
        });

        modelBuilder.Entity<Contact>(entity =>
        {
            entity.ToTable("Contacts");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Category).HasMaxLength(50).IsRequired();
            entity.Property(x => x.Name).HasMaxLength(100).IsRequired();
            entity.Property(x => x.Description).HasMaxLength(200);
            entity.Property(x => x.PhoneNumber).HasMaxLength(30);
            entity.Property(x => x.SecondaryNumber).HasMaxLength(30);
        });

        modelBuilder.Entity<Hospital>(entity =>
        {
            entity.ToTable("Hospitals");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Name).HasMaxLength(150).IsRequired();
            entity.Property(x => x.Address).HasMaxLength(250).IsRequired();
        });
    }
}
